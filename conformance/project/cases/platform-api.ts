import config from "../conformance.config";

function web(ctx: Context, name: string): any {
  return ctx.adapter[name] ?? ctx.adapter.window?.[name];
}

function xhr(ctx: Context, url: string, responseType: string): Promise<any> {
  return callback((resolve, reject) => {
    const XMLHttpRequest = web(ctx, "XMLHttpRequest");
    const request = new XMLHttpRequest();
    request.open("GET", url);
    request.responseType = responseType;
    request.onload = () => resolve(request.response);
    request.onerror = (error: unknown) => reject(error);
    request.send();
  }, `XMLHttpRequest ${responseType} ${url}`);
}

function loadImage(ctx: Context, src: string): Promise<any> {
  return callback((resolve, reject) => {
    const Image = web(ctx, "Image");
    const image = new Image();
    image.onload = () => resolve(image);
    image.onerror = (error: unknown) => reject(error);
    image.src = src;
  }, `Image ${src.slice(0, 64)}`);
}

// Generated by the runner from the same bytes as assets/red.png.
const RED_PNG_BASE64 = config.redPngBase64;

// Plain base64 decoding, so the cases do not depend on the API under test.
function base64ToBytes(_ctx: Context, base64: string): Uint8Array {
  const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
  const clean = base64.replace(/=+$/, "");
  const bytes = new Uint8Array(Math.floor((clean.length * 3) / 4));
  let bits = 0;
  let value = 0;
  let index = 0;
  for (const char of clean) {
    value = (value << 6) | alphabet.indexOf(char);
    bits += 6;
    if (bits >= 8) {
      bits -= 8;
      bytes[index++] = (value >> bits) & 0xff;
    }
  }
  return bytes;
}

